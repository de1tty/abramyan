V1 = float(input('Введите значение скорости первого автомобиля (км/ч): '))
V2 = float(input('Введите значение скорости второго автомобиля (км/ч): '))
T = float(input('Введите, сколько часов они ехали, приближаясь к друг другу: '))
S = float(input('Введите первоначальное расстояние между автомобилями: '))
if V1 < 0 or V2 < 0 or T < 0 or S < 0:
    print('скорость автомобилей, время и расстояние между ними не могут быть отрицательными')
else:
    S_itog = abs(S - ((V1 + V2) * T))
    print('через', T, 'часов автомобили будут друг от друга на расстоянии', S_itog)